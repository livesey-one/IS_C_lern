//--------------------------------------------------------24
// Копирует простые числа из A в B, в конец ставит 0
int f24(void) {
  int j, i, n, s, m;
  int A[100];
  int B[100];
  for (j = 0, i = 0; i < n; i++) {
    for (s = 0, m = 2; m < A[i]; m++)
      if (A[i] % m == 0) {
        s = 1;
        break;
      }
    if (s == 0)
      B[j++] = A[i];
  }
  B[j] = 0;
  return j;
}
//--------------------------------------------------------26
// Удаляет простые числа из массива A со сдвигом
int f26(void) {
  int j, i, n, m, s;
  int A[100];
  for (j = 0, i = 0; i < n; i++) {
    for (s = 0, m = 2; m < A[i]; m++)
      if (A[i] % m == 0) {
        s = 1;
        break;
      }
    if (s == 0) {
      for (j = i; j < n - 1; j++)
        A[j] = A[j + 1];
      n--;
      i--;
    }
  }
  return n;
}
//--------------------------------------------------------32
// Находит индекс первого вхождения наиболее частого элемента
int f32(void) {
  int s, i, n, k, j, b;
  int c[100];
  for (s = 0, i = 0; i < n; i++) {
    for (k = 0, j = 0; j < n; j++)
      if (c[i] == c[j])
        k++;
    if (k > s)
      s = k, b = i;
  }
  return b;
}
