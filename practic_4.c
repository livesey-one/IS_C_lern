/* ========================================================
   24
   Содержательный результат: Копирование всех простых чисел из массива A в
массив B (в конец ставится 0). Стандартные решения (паттерны):
   1. Линейный перебор элементов массива.
   2. Проверка числа на простоту (поиск делителя).
   3. Формирование нового массива (запись по независимому счетчику j).
======================================================== */
int f24(void) {
  int n = 5;
  int A[100] = {4, 7, 8, 11, 15};
  int B[100];
  int j, i, s, m;

  printf("24.\nВход: 4, 7, 8, 11, 15\n");

  for (j = 0, i = 0; i < n; i++) {
    for (s = 0, m = 2; m < A[i]; m++)
      if (A[i] % m == 0) {
        s = 1;
        break;
      }
    if (s == 0)
      B[j++] = A[i];
  }
  B[j] = 0;

  printf("Выход: ");
  for (int k = 0; k < j; k++)
    printf("%d ", B[k]);
  printf("\n\n");
  return j;
}

/* ========================================================
   26
   Содержательный результат: Удаление всех простых чисел из массива A.
   Стандартные решения (паттерны):
   1. Проверка числа на простоту.
   2. Удаление элемента из массива со сдвигом элементов влево.
   3. Корректировка итератора (i--) и размера (n--) при удалении.
======================================================== */
int f26(void) {
  int n = 5;
  int A[100] = {4, 7, 8, 11, 15};
  int j, i, m, s;

  printf("26.\nВход: 4, 7, 8, 11, 15\n");

  for (j = 0, i = 0; i < n; i++) {
    for (s = 0, m = 2; m < A[i]; m++)
      if (A[i] % m == 0) {
        s = 1;
        break;
      }
    if (s == 0) {
      for (j = i; j < n - 1; j++)
        A[j] = A[j + 1];
      n--;
      i--;
    }
  }

  printf("Выход: ");
  for (int k = 0; k < n; k++)
    printf("%d ", A[k]);
  printf("\n\n");
  return n;
}

/* ========================================================
   32
   Содержательный результат: Поиск индекса первого вхождения наиболее частого
элемента в массиве. Стандартные решения (паттерны):
   1. Вложенный цикл (перебор пар) для подсчета частоты каждого элемента.
   2. Поиск максимума (сохранение максимального счетчика s и индекса b).
======================================================== */
int f32(void) {
  int n = 6;
  int c[100] = {1, 2, 2, 3, 2, 1};
  int s, i, k, j, b;

  printf("32.\nВход: 1, 2, 2, 3, 2, 1\n");

  for (s = 0, i = 0; i < n; i++) {
    for (k = 0, j = 0; j < n; j++)
      if (c[i] == c[j])
        k++;
    if (k > s)
      s = k, b = i;
  }

  printf("Выход: %d\n\n", b);
  return b;
}

/* ========================================================
   34
   Содержательный результат: Вычисление целой части двоичного логарифма
(наибольшая степень двойки, не превышающая n). Стандартные решения (паттерны):
   1. Накопление произведения (m = m * 2).
   2. Использование переменной k как счетчика итераций.
======================================================== */
int f34(void) {
  int n = 10;
  int k, m;

  printf("34.\nВход: 10\n");

  for (k = 0, m = 1; m <= n; k++, m = m * 2)
    ;

  printf("Выход: %d\n\n", k - 1);
  return k - 1;
}

/* ========================================================
   36
   Содержательный результат: Поиск медианы в массиве без сортировки.
   Стандартные решения (паттерны):
   1. Вложенный цикл для подсравнения элемента со всеми остальными.
   2. Подсчет элементов меньше и больше текущего (k1, k2).
======================================================== */
int f36(void) {
  int n = 5;
  int c[100] = {10, 30, 20, 50, 40};
  int i, j, k1, k2;

  printf("36.\nВход: 10, 30, 20, 50, 40\n");

  for (i = 0; i < n; i++) {
    for (j = k1 = k2 = 0; j < n; j++)
      if (c[i] != c[j]) {
        if (c[i] < c[j])
          k1++;
        else
          k2++;
      }
    if (k1 == k2) {
      printf("Выход: %d\n\n", i);
      return i;
    }
  }

  printf("Выход: -1\n\n");
  return -1;
}

/* ========================================================
   38
   Содержательный результат: Нахождение начального индекса самой длинной серии
подряд идущих одинаковых элементов. Стандартные решения (паттерны):
   1. Просмотр пар соседних элементов (c[i] == c[i+1]).
   2. Поиск максимума длины серии (m) с сохранением вычисленного начального
индекса (b).
   3. Сброс счетчика серии при нарушении условия.
======================================================== */
int f38(void) {
  int n = 6;
  int c[100] = {1, 2, 2, 2, 3, 3};
  int i, k, m, b;

  printf("38.\nВход: 1, 2, 2, 2, 3, 3\n");

  for (i = k = m = 0; i < n - 1; i++)
    if (c[i] == c[i + 1])
      k++;
    else {
      if (k > m)
        m = k, b = i - k - 1;
      k = 0;
    }

  printf("Выход: %d\n\n", b);
  return b;
}

/* ========================================================
   42
   Содержательный результат: Балансировка сумм элементов массива с двух концов
(поиск точки разделения). Стандартные решения (паттерны):
   1. Встречное движение индексов (i с начала, j с конца).
   2. Накопление двух сумм (s1, s2) и выбор направления сдвига по условию
минимума.
======================================================== */
int f42(void) {
  int n = 5;
  int A[100] = {2, 1, 5, 2, 2};
  int s1, s2, i, j;

  printf("42.\nВход: 2, 1, 5, 2, 2\n");

  for (s1 = 0, s2 = 0, i = 0, j = n - 1; i <= j;) {
    if (s1 < s2)
      s1 += A[i], i++;
    else
      s2 += A[j], j--;
  }

  printf("Выход: %d\n\n", i);
  return i;
}

/* ========================================================
   47
   Содержательный результат: Отбор в массив A чисел от 10 до v-1, которые
делятся на каждую свою цифру. Стандартные решения (паттерны):
   1. Выделение цифр числа (деление и остаток от 10).
   2. Проверка делимости на цифру.
   3. Формирование нового массива по условию.
======================================================== */
int f47(void) {
  int v = 25;
  int A[100];
  int j, a, s, n, k;

  printf("47.\nВход: %d\n", v);

  for (j = 0, a = 10; a < v; a++) {
    for (s = 0, n = a, s = 0; n != 0; n = n / 10) {
      k = n % 10;
      if (k != 0 && a % k != 0) {
        s = 1;
        break;
      }
    }
    if (s == 0)
      A[j++] = a;
  }

  printf("Выход: ");
  for (int k_idx = 0; k_idx < j; k_idx++)
    printf("%d ", A[k_idx]);
  printf("\n\n");
  return j;
}

/* ========================================================
   49
   Содержательный результат: Поиск индекса минимального неотрицательного
элемента массива. Стандартные решения (паттерны):
   1. Фильтрация элементов (пропуск отрицательных с помощью continue).
   2. Поиск минимума с инициализацией флаговым значением (k=-1).
======================================================== */
int f49(void) {
  int A[10] = {-5, -2, 8, 3, -1, 9, 2, 7, -4, 5};
  int i, k;

  printf("49.\nВход: -5, -2, 8, 3, -1, 9, 2, 7, -4, 5\n");

  for (i = 0, k = -1; i < 10; i++) {
    if (A[i] < 0)
      continue;
    if (k == -1)
      k = i;
    else if (A[i] < A[k])
      k = i;
  }

  printf("Выход: %d\n\n", k);
  return k;
}

