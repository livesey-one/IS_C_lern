//--------------------------------------------------------36
// Ищет медиану: индекс элемента
int f36(void) {
  int i, n, j, k1, k2;
  int c[100];
  for (i = 0; i < n; i++) {
    for (j = k1 = k2 = 0; j < n; j++)
      if (c[i] != c[j]) {
        if (c[i] < c[j])
          k1++;
        else
          k2++;
      }
    if (k1 == k2)
      return i;
  }
  return -1;
}
//--------------------------------------------------------38
// Находит начальный индекс самой длинной серии подряд идущих одинаковых
// элементов
int f38(void) {
  int i, k, m, n, b;
  int c[100];
  for (i = k = m = 0; i < n - 1; i++)
    if (c[i] == c[i + 1])
      k++;
    else {
      if (k > m)
        m = k, b = i - k - 1;
      k = 0;
    }
  return b;
}
//--------------------------------------------------------42
// Балансирует сумму с двух концов, возвращая индекс точки разделения
int f42(void) {
  int s1, s2, i, j, n;
  int A[100];
  for (s1 = 0, s2 = 0, i = 0, j = n - 1; i <= j;) {
    if (s1 < s2)
      s1 += A[i], i++;
    else
      s2 += A[j], j--;
  }
  return i;
}
//--------------------------------------------------------47
// Отбирает в массив A числа от 10 до v-1, делящиеся на каждую свою цифру
int f47(void) {
  int j, a, v, s, n, k;
  int A[100];
  for (j = 0, a = 10; a < v; a++) {
    for (s = 0, n = a, s = 0; n != 0; n = n / 10) {
      k = n % 10;
      if (k != 0 && a % k != 0) {
        s = 1;
        break;
      }
    }
    if (s == 0)
      A[j++] = a;
  }
  return j;
}
//--------------------------------------------------------49
// Находит индекс минимального неотрицательного элемента
int f49(void) {
  int i, k;
  int A[10];
  for (i = 0, k = -1; i < 10; i++) {
    if (A[i] < 0)
      continue;
    if (k == -1)
      k = i;
    else if (A[i] < A[k])
      k = i;
  }
  return k;
}
//--------------------------------------------------------50
// Считает количество непрерывных наборов отрицательных чисел
int f50(void) {
  int i, s, k;
  int A[10];
  for (i = 0, s = 0, k = 0; i < 10; i++)
    if (A[i] < 0)
      k = 1;
    else {
      if (k == 1)
        s++;
      k = 0;
    }
  return s;
}
